export const LIBYA_CITIES = Object.keys(LIBYA_DELIVERY_CITIES_AREAS);

export function getAreasForCity(city) {
  if (!city || !LIBYA_DELIVERY_CITIES_AREAS[city]) return [];
  return LIBYA_DELIVERY_CITIES_AREAS[city].areas || [];
}

export function getDeliveryInfoForCity(city, customRates = null) {
  if (customRates && customRates[city]) {
    return {
      rate: Number(customRates[city].rate ?? customRates[city].cost ?? customRates[city]),
      days: Number(customRates[city].days ?? customRates[city].deliveryDays ?? 2)
    };
  }
  const defaultInfo = LIBYA_DELIVERY_CITIES_AREAS[city];
  if (defaultInfo) {
    return {
      rate: defaultInfo.defaultRate,
      days: defaultInfo.deliveryDays
    };
  }
  return { rate: 20, days: 2 };
}

export function formatDeliveryAddress({ city = "", area = "", addressDetails = "" }) {
  const safeArea = area && area !== city ? area : "";
  const parts = ["ليبيا", city, safeArea, addressDetails].filter(Boolean);
  return parts.join(" — ");
}